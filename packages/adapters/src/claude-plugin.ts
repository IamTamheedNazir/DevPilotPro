import {
  listBuiltinSkills,
  VERSION,
  type CanonicalSkill,
} from "@steward/core";

/**
 * Claude Code plugin + marketplace generation.
 *
 * Steward's normal install path writes thin per-project pointers into the
 * user's project (.claude/skills/...). A marketplace plugin is different: it
 * ships to any project via the plugin cache, so artifacts must be
 * SELF-CONTAINED — command and skill bodies embed the canonical skill text
 * instead of pointing at `.vibe/skills/`.
 *
 * Everything here is a deterministic transform of the canonical skill library,
 * so the committed plugin tree can be regenerated byte-for-byte
 * (`bun run plugin:check` in CI enforces this).
 */

export const MARKETPLACE_RELATIVE_DIR = ".claude-plugin";
export const MARKETPLACE_FILE = `${MARKETPLACE_RELATIVE_DIR}/marketplace.json`;
export const PLUGIN_DIR = "plugins/steward";
export const PLUGIN_NAME = "steward";

export interface GeneratedFile {
  /** Repo-root-relative path. */
  file: string;
  content: string;
}

function pluginSkillBody(skill: CanonicalSkill): string {
  return [
    `# Steward — ${skill.front.title}`,
    "",
    `> Canonical Steward skill \`${skill.front.id}\` v${skill.front.version}.`,
    `> ${skill.front.description}`,
    "",
    skill.body.trimEnd(),
    "",
    "---",
    "",
    "Apply this process exactly. Do not claim completion without the evidence this skill requires.",
    "Lifecycle state is deterministic: inspect with `steward status`, prove completion with `steward verify <feature>` — prose cannot change lifecycle state; only executed, recorded evidence can.",
    "",
  ].join("\n");
}

function pluginCommandBody(skill: CanonicalSkill): string {
  const lines = [
    `Read and follow the Steward skill '${skill.front.id}' (v${skill.front.version}, "${skill.front.title}").`,
    "",
    ...pluginSkillBody(skill).split("\n").slice(4), // strip the H1 + pointer block; command already names the skill
    "",
    "Skill arguments: $ARGUMENTS",
    "",
  ];
  return lines.join("\n");
}

