/** All marketplace/plugin files, derived purely from the canonical skills. */
export function generateClaudePlugin(): GeneratedFile[] {
  const skills = listBuiltinSkills();
  if (skills.length === 0) {
    throw new Error("no canonical skills found — refusing to generate an empty plugin");
  }

  const files: GeneratedFile[] = [
    { file: MARKETPLACE_FILE, content: marketplaceJson() },
    { file: `${PLUGIN_DIR}/.claude-plugin/plugin.json`, content: pluginJson() },
  ];

  for (const skill of skills) {
    files.push({
      file: `${PLUGIN_DIR}/commands/${skill.front.id}.md`,
      content: [
        "---",
        `description: ${JSON.stringify(skill.front.description)}`,
        "---",
        "",
        pluginCommandBody(skill),
      ].join("\n"),
    });
    files.push({
      file: `${PLUGIN_DIR}/skills/${skill.front.id}/SKILL.md`,
      content: [
        "---",
        `name: ${skill.front.id}`,
        `description: ${JSON.stringify(skill.front.description)}`,
        "---",
        "",
        pluginSkillBody(skill),
      ].join("\n"),
    });
  }

  return files;
}
